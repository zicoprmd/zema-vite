const toKey = (text) => text.toLowerCase();

const articleFor = (word) =>
  /^[aeiou]/i.test(word) ? `an ${word}` : `a ${word}`;

const buildExampleContent = (item, categoryKey) => {
  const englishKey = toKey(item.english);
  const indonesian = item.indonesian || lessonLexicon[englishKey] || item.english;

  if (categoryKey === "colors") {
    return {
      indonesian,
      exampleEnglish: `The color is ${englishKey}.`,
      exampleChinese: `这个颜色是${item.chinese}。`,
      exampleIndonesian: `Warnanya ${indonesian}.`,
    };
  }

  if (categoryKey === "numbers") {
    return {
      indonesian,
      exampleEnglish: `I can count ${englishKey}.`,
      exampleChinese: `我会数到${item.chinese}。`,
      exampleIndonesian: `Saya bisa menghitung sampai ${indonesian}.`,
    };
  }

  if (categoryKey === "actions") {
    return {
      indonesian,
      exampleEnglish: `I can ${englishKey}.`,
      exampleChinese: `我会${item.chinese}。`,
      exampleIndonesian: `Saya bisa ${indonesian}.`,
    };
  }

  if (categoryKey === "feelings") {
    return {
      indonesian,
      exampleEnglish: `I feel ${englishKey}.`,
      exampleChinese: `我觉得${item.chinese}。`,
      exampleIndonesian: `Saya merasa ${indonesian}.`,
    };
  }

  if (categoryKey === "weather") {
    return {
      indonesian,
      exampleEnglish: `Today is ${englishKey}.`,
      exampleChinese: `今天是${item.chinese}。`,
      exampleIndonesian: `Hari ini ${indonesian}.`,
    };
  }

  if (categoryKey === "dailyPhrases") {
    return {
      indonesian,
      exampleEnglish: `We say, "${item.english}."`,
      exampleChinese: `我们说“${item.chinese}”。`,
      exampleIndonesian: `Kita mengucapkan, "${indonesian}."`,
    };
  }

  if (categoryKey === "school") {
    return {
      indonesian,
      exampleEnglish: `This is my ${englishKey}.`,
      exampleChinese: `这是我的${item.chinese}。`,
      exampleIndonesian: `Ini ${indonesian} saya.`,
    };
  }

  return {
    indonesian,
    exampleEnglish: `This is ${articleFor(englishKey)}.`,
    exampleChinese: `这是${item.chinese}。`,
    exampleIndonesian: `Ini adalah ${indonesian}.`,
  };
};

const parseBaseContent = () => {
  const contentOnly = appScript.slice(0, appScript.indexOf("const quizPraise"));
  return Function(`${contentOnly}; return { categories, data };`)();
};

export const loadLessonContent = () => {
  const baseContent = parseBaseContent();

  const categories = [
    ...baseContent.categories,
    ...extraLessonPacks.categories.filter(
      (extraCategory) =>
        !baseContent.categories.some((item) => item.key === extraCategory.key),
    ),
  ];

  const rawData = {
    ...baseContent.data,
    ...extraLessonPacks.data,
  };

  const data = Object.fromEntries(
    Object.entries(rawData).map(([categoryKey, items]) => [
      categoryKey,
      items.map((item) => ({
        ...item,
        ...buildExampleContent(item, categoryKey),
      })),
    ]),
  );

  return { categories, data };
};

export const lessonContent = loadLessonContent();
